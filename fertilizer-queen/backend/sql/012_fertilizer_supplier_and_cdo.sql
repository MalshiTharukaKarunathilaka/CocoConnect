-- Fertilizer supplier and CDO registration profiles (linked to users).
-- Run in Supabase SQL editor (or auto-loaded by the memory DB).

CREATE TABLE IF NOT EXISTS fertilizer_suppliers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  shop_name varchar(120) NOT NULL,
  identity_number varchar(40) NOT NULL,
  email varchar(254),
  district varchar(60) NOT NULL,
  radius_km integer NOT NULL CHECK (radius_km IN (1, 5, 10)),
  willing_far boolean NOT NULL DEFAULT false,
  shop_type varchar(30) NOT NULL DEFAULT 'Physical shop'
    CHECK (shop_type IN ('Physical shop', 'Delivery-only')),
  brands varchar(200) NOT NULL DEFAULT '',
  coverage_note text NOT NULL DEFAULT '',
  terms_accepted_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS cdo_officers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  identity_number varchar(40) NOT NULL,
  email varchar(254) NOT NULL,
  employee_id varchar(60) NOT NULL,
  designation varchar(120) NOT NULL DEFAULT 'Coconut Development Officer',
  regional_office varchar(120) NOT NULL,
  assigned_district varchar(60) NOT NULL,
  assigned_divisional_areas text NOT NULL,
  id_card_filename varchar(255),
  employment_doc_filename varchar(255),
  terms_accepted_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE fertilizer_suppliers ENABLE ROW LEVEL SECURITY;
ALTER TABLE cdo_officers ENABLE ROW LEVEL SECURITY;
