const router = require('express').Router();
const {requireAuth,requireRole} = require('../middleware/auth');
const c = require('../controllers/machineryController');
router.use(requireAuth);
router.get('/catalog',c.catalog);
router.get('/provider/machines',requireRole('SERVICE_PROVIDER'),c.providerMachines);
router.post('/provider/machines',requireRole('SERVICE_PROVIDER'),c.createMachine);
router.put('/provider/machines/:machineId/rates',requireRole('SERVICE_PROVIDER'),c.saveRate);
router.get('/provider/machines/:machineId/calendar',requireRole('SERVICE_PROVIDER'),c.calendar);
router.put('/provider/machines/:machineId/availability',requireRole('SERVICE_PROVIDER'),c.setAvailability);
router.get('/machines/:machineId/calendar',requireRole('ESTATE_OWNER'),c.ownerCalendar);
router.get('/machines',requireRole('ESTATE_OWNER'),c.browse);
router.post('/machines/:machineId/bookings',requireRole('ESTATE_OWNER'),c.createBooking);
router.get('/bookings',requireRole('ESTATE_OWNER'),c.myBookings);
router.get('/bookings/:bookingId',c.getBooking);
router.post('/bookings/:bookingId/messages',c.message);
router.post('/bookings/:bookingId/agree',c.agree);
router.post('/bookings/:bookingId/revise',requireRole('ESTATE_OWNER'),c.revise);
router.post('/bookings/:bookingId/accept',requireRole('SERVICE_PROVIDER'),c.accept);
router.post('/bookings/:bookingId/cancel',requireRole('ESTATE_OWNER'),c.cancel);
router.post('/bookings/:bookingId/decline',requireRole('SERVICE_PROVIDER'),c.decline);
module.exports=router;
